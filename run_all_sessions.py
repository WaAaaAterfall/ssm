"""Run the full perturbation-PLDS validation pipeline across many sessions.

For each session it:
  1. fits the PLDS at p=10 and caches everything -> session{N}/fit_p10.pkl
     (skipped if the cache already exists, so the job is resumable);
  2. runs the three-method validation (A off-manifold angle, B effective
     dimensionality, C counterfactual mechanism) -> validate_*.png;
  3. reproduces the old calcium off-plane *drive*-angle (Plot 2), with the
     onset-aligned, whole-trial and k-sweep variants -> validate_A_drive_*.png;
  4. writes per-session validate_report.md and drive_angle_report.md filled with
     that session's numbers; and appends a row to a top-level summary table.

Penalty is fixed at lam=1e-3 (not tuned) for cross-session comparability.

Run (long; ~12-15 min fit per session) in the background:
    /home/sp645/miniconda3/envs/ssm/bin/python run_all_sessions.py --sessions 1-7
"""

import argparse
import os
import time
import traceback

import fit_p10_cache as fitc
import run_manifold_analysis as mani
import run_taskA_drive_angle as drive

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                    "perturbation_plds_results")


def _p(x):
    """Format a p-value compactly."""
    return f"{x:.2e}" if x < 1e-3 else f"{x:.3f}"



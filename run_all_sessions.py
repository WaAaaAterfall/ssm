        f"- Unperturbed manifold dimension (90% var, train half): **k = {s['k']}**.",
        f"- Median perturbation onset (trimmed): bin {s['med_onset']}; "
        f"final ELBO {s['elbo']:,.0f}.",
        "",
        "## A. Off-manifold angle (perturbed leaves the unperturbed manifold)",

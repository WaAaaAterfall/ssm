def parse_sessions(spec):
    out = []
    for part in spec.split(","):
        part = part.strip()
        if "-" in part:
            a, b = part.split("-")
            out.extend(range(int(a), int(b) + 1))
        elif part:
            out.append(int(part))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sessions", type=str, default="1-7",
                    help="e.g. '1-7' or '1,3,5'")
    ap.add_argument("--refit", action="store_true",
                    help="refit even if fit_p10.pkl already exists")
    args = ap.parse_args()
    sessions = parse_sessions(args.sessions)
    print(f"=== run_all_sessions: sessions {sessions} ===", flush=True)

    summary = []  # (session, ok, note)
    for sess in sessions:
        t0 = time.time()
        outdir = os.path.join(ROOT, f"session{sess}")
        os.makedirs(outdir, exist_ok=True)
        cache_path = os.path.join(outdir, "fit_p10.pkl")
        print(f"\n########## SESSION {sess} ##########", flush=True)
        try:
            if args.refit or not os.path.exists(cache_path):
                fitc.fit_and_cache(sess, cache_path)
            else:
                print(f"[s{sess}] cache exists, skipping fit", flush=True)

            mstats = mani.run(cache_path, outdir)
            write_validate_report(outdir, sess, mstats)

            dstats = drive.run(cache_path, outdir)
            write_drive_report(outdir, sess, dstats)

            note = (f"p={mstats['p']} k={mstats['k']} "
                    f"A:{mstats['A']['post']:.1f}/{mstats['A']['unp']:.1f}° "
                    f"drive:{dstats['whole']['pert']:.1f}/{dstats['whole']['ctrl']:.1f}°")
            summary.append((sess, True, note))
            print(f"[s{sess}] DONE in {(time.time()-t0)/60:.1f} min — {note}", flush=True)
        except Exception as e:
            tb = traceback.format_exc()
            summary.append((sess, False, str(e)))
            print(f"[s{sess}] FAILED: {e}\n{tb}", flush=True)

    # top-level summary
    lines = ["# Multi-session run summary", "",
             f"*Generated {time.strftime('%Y-%m-%d %H:%M')} by `run_all_sessions.py`.*", "",
             "| session | status | notes |", "|---|---|---|"]
    for sess, ok, note in summary:
        lines.append(f"| {sess} | {'ok' if ok else 'FAILED'} | {note} |")
    with open(os.path.join(ROOT, "all_sessions_summary.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"\n=== summary written to {ROOT}/all_sessions_summary.md ===", flush=True)


if __name__ == "__main__":
    main()
